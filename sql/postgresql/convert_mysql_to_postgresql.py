#!/usr/bin/env python3
"""Generate PostgreSQL 17 initialization scripts from the maintained MySQL SQL files."""

from __future__ import annotations

import hashlib
import re
from pathlib import Path


SQL_DIR = Path(__file__).resolve().parent.parent
OUTPUT_DIR = Path(__file__).resolve().parent

CREATE_TABLE_RE = re.compile(
    r"^CREATE TABLE (?P<if_not_exists>IF NOT EXISTS )?`(?P<table>[^`]+)`\s*\($",
    re.IGNORECASE,
)
INDEX_RE = re.compile(
    r"^\s*(?P<unique>UNIQUE\s+)?(?P<fulltext>FULLTEXT\s+)?INDEX\s+`(?P<name>[^`]+)`\s*"
    r"\((?P<columns>.*)\)\s*(?:WITH PARSER\s+\w+\s*)?(?:USING BTREE\s*)?,?\s*$",
    re.IGNORECASE,
)
COMMENT_RE = re.compile(r"\s+COMMENT\s+'(?:\\.|''|[^'])*'", re.IGNORECASE)
CHARSET_RE = re.compile(r"\s+CHARACTER SET\s+\w+", re.IGNORECASE)
COLLATE_RE = re.compile(r"\s+COLLATE\s+\w+", re.IGNORECASE)
AFTER_RE = re.compile(r"\s+AFTER\s+`[^`]+`", re.IGNORECASE)


def quoted_identifier(value: str) -> str:
    return f'"{value}"'


def postgres_index_name(table: str, name: str) -> str:
    candidate = f"{table}_{name}"
    if len(candidate.encode("utf-8")) <= 63:
        return candidate
    digest = hashlib.sha1(candidate.encode("utf-8")).hexdigest()[:8]
    return f"{candidate[:54]}_{digest}"


def replace_identifiers(sql: str) -> str:
    return re.sub(r"`([^`]+)`", lambda match: quoted_identifier(match.group(1)), sql)


def convert_definition(line: str) -> str:
    line = COMMENT_RE.sub("", line)
    line = CHARSET_RE.sub("", line)
    line = COLLATE_RE.sub("", line)
    line = AFTER_RE.sub("", line)
    line = re.sub(r"\bUNSIGNED\b", "", line, flags=re.IGNORECASE)
    line = re.sub(r"\bAUTO_INCREMENT\b", "GENERATED BY DEFAULT AS IDENTITY", line, flags=re.IGNORECASE)
    line = re.sub(r"\bdatetime\s*\((\d+)\)", r"timestamp(\1)", line, flags=re.IGNORECASE)
    line = re.sub(r"\bdatetime\b", "timestamp", line, flags=re.IGNORECASE)
    line = re.sub(r"\btinyint(?:\s*\(\d+\))?", "smallint", line, flags=re.IGNORECASE)
    line = re.sub(r"\bmediumint(?:\s*\(\d+\))?", "integer", line, flags=re.IGNORECASE)
    line = re.sub(r"\b(?:longtext|mediumtext)\b", "text", line, flags=re.IGNORECASE)
    line = re.sub(r"\bdouble\b(?!\s+precision)", "double precision", line, flags=re.IGNORECASE)
    line = re.sub(r"\bfloat\b", "real", line, flags=re.IGNORECASE)
    line = re.sub(r"\bblob\b", "bytea", line, flags=re.IGNORECASE)
    line = re.sub(r"\s+ON UPDATE CURRENT_TIMESTAMP(?:\(\d+\))?", "", line, flags=re.IGNORECASE)
    line = re.sub(r"\s+USING BTREE", "", line, flags=re.IGNORECASE)
    line = re.sub(r"\bDEFAULT\s+b'([01]+)'", r"DEFAULT B'\1'", line, flags=re.IGNORECASE)
    line = re.sub(r"[ \t]+", " ", line).rstrip()
    return replace_identifiers(line)


def split_actions(value: str) -> list[str]:
    actions: list[str] = []
    start = 0
    depth = 0
    in_string = False
    escaped = False
    for index, char in enumerate(value):
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == "'":
                in_string = False
            continue
        if char == "'":
            in_string = True
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            actions.append(value[start:index].strip())
            start = index + 1
    actions.append(value[start:].strip())
    return actions


def convert_alter(statement: str) -> list[str]:
    match = re.match(r"ALTER TABLE\s+`([^`]+)`\s+(.*);\s*$", statement, re.IGNORECASE | re.DOTALL)
    if not match:
        raise ValueError(f"Unsupported ALTER TABLE statement: {statement[:120]}")
    table, body = match.groups()
    converted: list[str] = []
    for action in split_actions(body):
        drop_match = re.match(r"DROP INDEX\s+`([^`]+)`$", action, re.IGNORECASE)
        index_match = re.match(
            r"ADD\s+(UNIQUE\s+)?INDEX\s+`([^`]+)`\s*\((.*)\)(?:\s+USING BTREE)?$",
            action,
            re.IGNORECASE | re.DOTALL,
        )
        modify_match = re.match(r"MODIFY COLUMN\s+`([^`]+)`\s+(.*)$", action, re.IGNORECASE | re.DOTALL)
        if drop_match:
            name = postgres_index_name(table, drop_match.group(1))
            converted.append(f'DROP INDEX IF EXISTS {quoted_identifier(name)};')
        elif index_match:
            unique = "UNIQUE " if index_match.group(1) else ""
            name = postgres_index_name(table, index_match.group(2))
            columns = convert_definition(index_match.group(3))
            converted.append(
                f'CREATE {unique}INDEX IF NOT EXISTS {quoted_identifier(name)} '
                f'ON {quoted_identifier(table)} ({columns});'
            )
        elif modify_match:
            column, definition = modify_match.groups()
            definition = convert_definition(definition)
            data_type = re.split(r"\s+(?:NULL|NOT NULL|DEFAULT)\b", definition, maxsplit=1, flags=re.IGNORECASE)[0]
            converted.append(
                f'ALTER TABLE {quoted_identifier(table)} ALTER COLUMN {quoted_identifier(column)} '
                f'TYPE {data_type};'
            )
        else:
            cleaned = convert_definition(action)
            cleaned = re.sub(r"^ADD COLUMN\s+", "ADD COLUMN IF NOT EXISTS ", cleaned, flags=re.IGNORECASE)
            converted.append(f'ALTER TABLE {quoted_identifier(table)} {cleaned};')
    return converted


class Converter:
    def __init__(self) -> None:
        self.identity_columns: set[tuple[str, str]] = set()

    def convert(self, source: Path, *, include_alters: bool = True) -> str:
        lines = source.read_text(encoding="utf-8").splitlines()
        output: list[str] = [f"-- Converted from ../{source.name} for PostgreSQL 17."]
        table: str | None = None
        table_if_not_exists = False
        definitions: list[str] = []
        indexes: list[tuple[str, str, str]] = []
        alter_lines: list[str] = []
        in_block_comment = False

        index = 0
        while index < len(lines):
            raw = lines[index]
            stripped = raw.strip()

            if in_block_comment:
                if "*/" in stripped:
                    in_block_comment = False
                index += 1
                continue
            if stripped.startswith("/*"):
                in_block_comment = "*/" not in stripped
                index += 1
                continue

            if table is not None:
                if stripped.startswith(") ENGINE") or stripped.startswith(")ENGINE"):
                    output.append(
                        f'CREATE TABLE {"IF NOT EXISTS " if table_if_not_exists else ""}'
                        f'{quoted_identifier(table)} ('
                    )
                    output.extend(
                        f"  {definition.rstrip(',')}" + ("," if pos < len(definitions) - 1 else "")
                        for pos, definition in enumerate(definitions)
                    )
                    output.append(");")
                    for unique, name, columns in indexes:
                        pg_name = postgres_index_name(table, name)
                        output.append(
                            f'CREATE {unique}INDEX {"IF NOT EXISTS " if table_if_not_exists else ""}'
                            f'{quoted_identifier(pg_name)} ON {quoted_identifier(table)} ({columns});'
                        )
                    output.append("")
                    table = None
                    definitions = []
                    indexes = []
                    index += 1
                    continue

                index_match = INDEX_RE.match(raw)
                if index_match:
                    if index_match.group("fulltext"):
                        output.append(
                            f"-- Skipped MySQL ngram FULLTEXT index {index_match.group('name')}; "
                            "the application uses weighted LIKE search."
                        )
                    else:
                        unique = "UNIQUE " if index_match.group("unique") else ""
                        columns = convert_definition(index_match.group("columns"))
                        indexes.append((unique, index_match.group("name"), columns))
                    index += 1
                    continue

                definition = convert_definition(raw.strip())
                identity_match = re.match(
                    r'^"([^"]+)"\s+\S+.*GENERATED BY DEFAULT AS IDENTITY',
                    definition,
                    re.IGNORECASE,
                )
                if identity_match:
                    self.identity_columns.add((table, identity_match.group(1)))
                definitions.append(definition)
                index += 1
                continue

            create_match = CREATE_TABLE_RE.match(stripped)
            if create_match:
                table = create_match.group("table")
                table_if_not_exists = bool(create_match.group("if_not_exists"))
                index += 1
                continue

            if stripped.upper().startswith("ALTER TABLE"):
                alter_lines = [raw]
                while ";" not in alter_lines[-1] and index + 1 < len(lines):
                    index += 1
                    alter_lines.append(lines[index])
                if include_alters:
                    output.extend(convert_alter("\n".join(alter_lines)))
                    output.append("")
                index += 1
                continue

            if (
                not stripped
                or stripped.startswith("--")
                or stripped.startswith("*")
                or stripped.startswith("*/")
            ):
                if stripped.startswith("--"):
                    output.append(raw)
                elif not stripped and output and output[-1] != "":
                    output.append("")
                index += 1
                continue

            upper = stripped.upper()
            if upper.startswith("SET NAMES") or upper.startswith("SET FOREIGN_KEY_CHECKS"):
                index += 1
                continue
            if upper in {"START TRANSACTION;", "BEGIN;", "COMMIT;"}:
                index += 1
                continue
            if upper.startswith("DROP TABLE") or upper.startswith("INSERT INTO") or upper.startswith("UPDATE ") or upper.startswith("DELETE FROM") or alter_lines:
                output.append(replace_identifiers(raw))
            else:
                output.append(replace_identifiers(raw))
            index += 1

        return "\n".join(output).rstrip() + "\n"


def write_script(name: str, body: str) -> None:
    header = (
        "\\set ON_ERROR_STOP on\n"
        "SET client_encoding = 'UTF8';\n"
        "SET standard_conforming_strings = off;\n\n"
        "SET escape_string_warning = off;\n\n"
    )
    (OUTPUT_DIR / name).write_text(header + body, encoding="utf-8")


def sequence_script(identity_columns: set[tuple[str, str]]) -> str:
    sequence_lines = [
        "-- Advance identity sequences past explicitly imported IDs.",
        "DO $sync_sequences$",
        "DECLARE",
        "  next_value bigint;",
        "BEGIN",
    ]
    for table, column in sorted(identity_columns):
        sequence_lines.extend(
            [
                f'  SELECT COALESCE(MAX({quoted_identifier(column)}), 0) + 1 INTO next_value FROM {quoted_identifier(table)};',
                f"  PERFORM setval(pg_get_serial_sequence('{table}', '{column}'), next_value, false);",
            ]
        )
    sequence_lines.extend(["END", "$sync_sequences$;", ""])
    return "\n".join(sequence_lines)


def main() -> None:
    converter = Converter()
    write_script("00_h_boot_schema_data.sql", converter.convert(SQL_DIR / "h_boot.sql"))
    base_identity_columns = set(converter.identity_columns)
    write_script("05_sync_base_sequences.sql", sequence_script(base_identity_columns))
    write_script("10_knowledge_base_v1.sql", converter.convert(SQL_DIR / "knowledge_base_v1.sql"))
    write_script("20_photo_album_v1.sql", converter.convert(SQL_DIR / "photo_album_v1.sql"))
    write_script(
        "30_sa_token_permission_patch_20260604.sql",
        converter.convert(SQL_DIR / "sa_token_permission_patch_20260604.sql"),
    )

    warm_flow = """-- The current h_boot.sql already contains the Warm Flow 1.8.5 columns and indexes.
-- Keep the data corrections from update_warm_flow_1_8_5.sql idempotent.
UPDATE "flow_skip"
SET "skip_condition" = REPLACE("skip_condition", 'notNike', 'notLike')
WHERE "skip_condition" LIKE '%notNike%';

UPDATE "sys_menu" SET "permission" = 'workflow:definition:list'
WHERE "component" = 'workflow/processDefinition/index';
UPDATE "sys_menu" SET "permission" = 'workflow:instance:list'
WHERE "component" = 'workflow/processInstance/index';
UPDATE "sys_menu" SET "permission" = 'workflow:instance:currentList'
WHERE "component" = 'workflow/task/myDocument';
DELETE FROM "sys_menu"
WHERE "component" = 'workflow/processDefinition/design' OR "path" = '/design/index';
"""
    write_script("40_update_warm_flow_1_8_5.sql", warm_flow)

    audit = (SQL_DIR / "sql_audit_index_recommendations_20260605.sql").read_text(encoding="utf-8")
    audit = re.sub(r"CREATE INDEX\s+", "CREATE INDEX IF NOT EXISTS ", audit, flags=re.IGNORECASE)
    write_script("50_sql_audit_indexes.sql", audit)

    write_script("99_sync_sequences.sql", sequence_script(converter.identity_columns))


if __name__ == "__main__":
    main()
